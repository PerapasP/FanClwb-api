  /**
   * Create (schedule) a new live stream.
   * Only users with a verified artist_account linked to the fandom's artist can create.
   */
  async createStream(userId: string, dto: CreateStreamDto) {
    // 1. Verify user has artist_account
    const artistAccount = await this.prisma.artist_accounts.findUnique({
      where: { user_id: userId },
    });
    if (!artistAccount) {
      throw new ForbiddenException(
        'Only artist accounts can create live streams',
      );
    }

    // 2. Verify fandom exists and belongs to the same artist (if provided)
    if (dto.fandom_id) {
      const fandom = await this.prisma.fandoms.findUnique({
        where: { fandom_id: dto.fandom_id },
      });
      if (!fandom) throw new NotFoundException('Fandom not found');

      // Artist must be the group artist or solo artist linked to this fandom
      if (artistAccount.artist_id !== fandom.artist_id) {
        throw new ForbiddenException('You can only stream in your own fandom');
      }
    }

    // 3. Prevent duplicate live/scheduled streams per artist/fandom
    const existingLive = await this.prisma.live_streams.findFirst({
      where: {
        host_user_id: userId,
        fandom_id: dto.fandom_id ?? null,
        status: { in: ['live', 'scheduled'] },
      },
    });
    if (existingLive) {
      throw new ConflictException(
        'There is already an active or scheduled stream for this account/fandom',
      );
    }

    // 4. Create stream — stream_key auto-generated by DB default
    const stream = await this.prisma.live_streams.create({
      data: {
        fandom_id: dto.fandom_id ?? null,
        host_user_id: userId,
        title: dto.title,
        description: dto.description ?? null,
        thumbnail_url: dto.thumbnail_url ?? null,
        is_portrait: dto.is_portrait ?? false,
        scheduled_at: dto.scheduled_at ? new Date(dto.scheduled_at) : null,
      },
    });

    // Build RTMP/HLS URLs from env
    const rtmpHost = process.env.SRS_RTMP_HOST;
    const httpHost = process.env.SRS_HTTP_HOST;
    
    if (rtmpHost && httpHost) {
      const rtmp_url = `rtmp://${rtmpHost}/live/${stream.stream_key}`;
      const hls_url = `https://${httpHost}/live/${stream.stream_key}.m3u8`;
      return this.prisma.live_streams.update({
        where: { stream_id: stream.stream_id },
        data: { rtmp_url, hls_url },
      });
    }

    return stream;
  }

  /** Update stream metadata (title, description, thumbnail, scheduled_at) */
  async updateStream(userId: string, streamId: string, dto: UpdateStreamDto) {
    const stream = await this.findStreamOrFail(streamId);
    this.assertIsHost(stream.host_user_id, userId);

    if (stream.status === 'ended' || stream.status === 'cancelled') {
      throw new BadRequestException('Cannot edit a finished stream');
    }

    return this.prisma.live_streams.update({
      where: { stream_id: streamId },
      data: {
        ...(dto.title && { title: dto.title }),
        ...(dto.description !== undefined && { description: dto.description }),
        ...(dto.thumbnail_url !== undefined && {
          thumbnail_url: dto.thumbnail_url,
        }),
        ...(dto.scheduled_at
          ? { scheduled_at: new Date(dto.scheduled_at) }
          : {}),
      },
    });
  }

  /** Go live — changes status from scheduled → live and sets started_at */
  async startStream(userId: string, streamId: string) {
    const stream = await this.findStreamOrFail(streamId);
    this.assertIsHost(stream.host_user_id, userId);

    if (stream.status !== 'scheduled') {
      throw new BadRequestException(
        `Cannot start a stream with status "${stream.status}"`,
      );
    }

    return this.prisma.live_streams.update({
      where: { stream_id: streamId },
      data: { status: 'live', started_at: new Date() },
    });
  }

  /** End a live stream */
  async endStream(userId: string, streamId: string) {
    const stream = await this.findStreamOrFail(streamId);
    this.assertIsHost(stream.host_user_id, userId);

    if (stream.status !== 'live') {
      throw new BadRequestException('Stream is not currently live');
    }

    return this.prisma.live_streams.update({
      where: { stream_id: streamId },
      data: { status: 'ended', ended_at: new Date(), is_ingesting: false },
    });
  }

  /** Cancel a scheduled stream */
  async cancelStream(userId: string, streamId: string) {
    const stream = await this.findStreamOrFail(streamId);
    this.assertIsHost(stream.host_user_id, userId);

    if (stream.status === 'live') {
      throw new BadRequestException(
        'Cannot cancel a live stream. End it instead.',
      );
    }
    if (stream.status === 'ended' || stream.status === 'cancelled') {
      throw new BadRequestException('Stream is already finished');
    }

    return this.prisma.live_streams.update({
      where: { stream_id: streamId },
      data: { status: 'cancelled', is_ingesting: false },
    });
  }

