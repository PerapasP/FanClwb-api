  /** Look up a stream by its unique stream_key (used by SRS webhooks) */
  async getStreamByKey(streamKey: string) {
    return this.prisma.live_streams.findUnique({
      where: { stream_key: streamKey },
    });
  }


  private async findStreamOrFail(
    streamId: string,
    include?: Record<string, unknown>,
  ) {
    const stream = await this.prisma.live_streams.findUnique({
      where: { stream_id: streamId },
      ...(include ? { include } : {}),
    });
    if (!stream) throw new NotFoundException('Stream not found');
    return stream;
  }

  private assertIsHost(hostUserId: string, requestUserId: string) {
    if (hostUserId !== requestUserId) {
      throw new ForbiddenException(
        'Only the stream host can perform this action',
      );
    }
  }
