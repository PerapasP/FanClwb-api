  // Viewer tracking (called by WebSocket gateway)
  // ──────────────────────────────────────────────────────────

  async joinStream(streamId: string, userId: string): Promise<number> {
    const stream = await this.findStreamOrFail(streamId);
    if (stream.status !== 'live') {
      return 0; // Allow joining for preview, but don't track viewers yet
    }

    await this.prisma.stream_viewers.upsert({
      where: { stream_id_user_id: { stream_id: streamId, user_id: userId } },
      create: { stream_id: streamId, user_id: userId },
      update: { joined_at: new Date(), left_at: null },
    });

    const updated = await this.prisma.live_streams.update({
      where: { stream_id: streamId },
      data: {
        viewer_count: { increment: 1 },
      },
      select: { viewer_count: true, peak_viewer_count: true },
    });

    // Update peak if needed
    if (updated.viewer_count > updated.peak_viewer_count) {
      await this.prisma.live_streams.update({
        where: { stream_id: streamId },
        data: { peak_viewer_count: updated.viewer_count },
      });
    }

    return updated.viewer_count;
  }

  async leaveStream(streamId: string, userId: string): Promise<number> {
    await this.prisma.stream_viewers.updateMany({
      where: { stream_id: streamId, user_id: userId, left_at: null },
      data: { left_at: new Date() },
    });

    const updated = await this.prisma.live_streams.update({
      where: { stream_id: streamId },
      data: { viewer_count: { decrement: 1 } },
      select: { viewer_count: true },
    });

    // Clamp to 0
    if (updated.viewer_count < 0) {
      await this.prisma.live_streams.update({
        where: { stream_id: streamId },
        data: { viewer_count: 0 },
      });
      return 0;
    }

    return updated.viewer_count;
  }

