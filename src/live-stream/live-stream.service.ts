  async getGiftLeaderboard(streamId: string): Promise<GiftLeaderboardEntry[]> {
    await this.findStreamOrFail(streamId);

    const results = await this.prisma.stream_gifts.groupBy({
      by: ['sender_id'],
      where: { stream_id: streamId },
      _sum: { total_coins: true },
      _count: { gift_id: true },
      orderBy: { _sum: { total_coins: 'desc' } },
      take: 20,
    });

    const userIds = results.map((r) => r.sender_id);
    const users = await this.prisma.users.findMany({
      where: { user_id: { in: userIds } },
      select: { user_id: true, fullname: true, image_url: true },
    });
    const userMap = new Map(users.map((u) => [u.user_id, { fullname: u.fullname, image_url: u.image_url }]));

    return results.map((r) => {
      const u = userMap.get(r.sender_id);
      return {
        sender_id: r.sender_id,
        fullname: u?.fullname ?? null,
        image_url: u?.image_url ?? null,
        total_coins: r._sum.total_coins ?? 0,
        gift_count: r._count.gift_id,
      };
    });
  }

